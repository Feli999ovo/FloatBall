from ui_support import check, enable_model


async def test_handoff(orb_page):
    pg, shot, _ = orb_page
    await enable_model(pg)
    await pg.click('#orb')
    await pg.fill('#ask', '整理一份交接说明')
    await pg.press('#ask', 'Enter')
    await pg.wait_for_selector('.m.ai .meta:not([hidden])')
    # 9c 交给终端（B4）：… 菜单打开；只列本机装了的；要粘贴的先说清楚；交接说明从对话整理、可以改；默认存进项目
    await pg.evaluate("""__mock.hoScan = { tools: [{ id: 'claude', name: 'Claude Code', bin: 'claude', direct: true }, { id: 'kimi', name: 'Kimi Code CLI', bin: 'kimi', direct: false }],
      terms: [{ id: 'wt', name: 'Windows Terminal' }, { id: 'powershell', name: 'Windows PowerShell' }] }; __mock.hoPick = 'D:\\\\code\\\\FloatBall'""")
    await pg.click("#moreBtn"); await pg.wait_for_timeout(150)
    await pg.click("#moreDd [data-cm=ho]"); await pg.wait_for_timeout(300)
    g = await pg.evaluate("[!document.querySelector('#vHo').hidden, document.querySelector('#vChat').hidden, document.activeElement.id, [...document.querySelector('#hoTo').options].map(o => o.textContent), document.querySelector('#hoToN').textContent, document.querySelector('#hoMd').hidden, document.querySelector('#hoMdS').textContent]")
    check(g[:3] == [True, True, "hoTo"], f"… 菜单「交给终端」打开面板，光标在「交给」 {g[:3]}")
    check(g[3] == ["Claude Code", "Kimi Code CLI（打开后粘贴一次）", "自定义命令"], f"只列本机装了的，要粘贴的在选之前就标出来 {g[3]}")
    check(g[4] == "打开时直接带上交接说明", f"能直接带上的说一声 {g[4]}")
    check(g[5] and g[6] and not g[6].startswith("#"), f"交接说明先收成一句摘要（卡片只有 260 高） {g[6]!r}")
    await pg.click("#hoEdit"); await pg.wait_for_timeout(100)
    check(await pg.evaluate("[document.querySelector('#hoMd').hidden, document.activeElement.id, document.querySelector('#hoEdit').getAttribute('aria-expanded')]") == [False, "hoMd", "true"], "点「查看和修改」展开整段，光标进去")
    md = await pg.input_value("#hoMd")
    check(md.startswith("# 交接说明") and "## 要做什么" in md and "## 下一步" in md, f"交接说明从这次对话整理 {md[:60]!r}")
    check(await pg.evaluate("[document.querySelector('#hoSave').getAttribute('aria-checked'), document.querySelector('#hoGo').disabled]") == ["true", True], "默认存进项目；没选项目文件夹时不能打开")
    await pg.select_option("#hoTo", "kimi"); await pg.wait_for_timeout(50)
    check("Ctrl+V" in await pg.text_content("#hoToN"), "选了要粘贴的：说清楚打开后按 Ctrl+V")
    await pg.select_option("#hoTo", "custom"); await pg.wait_for_timeout(50)
    check(await pg.is_visible("#hoCustom"), "选「自定义命令」出输入框")
    await pg.select_option("#hoTo", "claude")
    await pg.click("#hoPick"); await pg.wait_for_timeout(150)
    check(await pg.evaluate("[document.querySelector('#hoDir').value, document.querySelector('#hoGo').disabled]") == ["D:\\code\\FloatBall", False], "选好项目文件夹后可以打开")
    await pg.fill("#hoMd", md + "\n补充：先跑测试")
    await pg.click("#hoGo"); await pg.wait_for_timeout(300)
    go = await pg.evaluate("__mock.hoGo[0]")
    check((go["tool"], go["term"], go["dir"], go["save"]) == ("claude", "wt", "D:\\code\\FloatBall", True) and go["md"].endswith("补充：先跑测试"), f"打开终端：交给选好的工具、终端、文件夹，带上改过的说明 {go['tool']} {go['term']}")
    check(await pg.evaluate("[document.querySelector('#vHo').hidden, !document.querySelector('#vChat').hidden, document.querySelector('#toast').textContent]") == [True, True, "终端已打开，由它接手"], "打开后回到对话，提示由它接手")
    # 再打开：记得上次的工具和文件夹；选 Kimi 打开后把那句话放进剪贴板
    await pg.click("#moreBtn"); await pg.wait_for_timeout(150)
    await pg.click("#moreDd [data-cm=ho]"); await pg.wait_for_timeout(300)
    check(await pg.evaluate("[document.querySelector('#hoTo').value, document.querySelector('#hoDir').value]") == ["claude", "D:\\code\\FloatBall"], "再打开时记得上次的工具和项目文件夹")
    await pg.select_option("#hoTo", "kimi"); await pg.click("#hoSave")
    await pg.evaluate("window.__clip = null; navigator.clipboard.writeText = async (t) => { window.__clip = t; }")
    await pg.click("#hoGo"); await pg.wait_for_timeout(300)
    g = await pg.evaluate("[__mock.hoGo[1].save, window.__clip, document.querySelector('#toast').textContent]")
    check(g[0] is False and g[1] and "handoff-1.md" in g[1] and "Ctrl+V" in g[2], f"关掉「存进项目」；要粘贴的把那句话放进剪贴板 {g}")
    await pg.click("#moreBtn"); await pg.wait_for_timeout(150)
    await pg.click("#moreDd [data-cm=ho]"); await pg.wait_for_timeout(300)
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(100)
    check(await pg.evaluate("[document.querySelector('#vHo').hidden, !document.querySelector('#vChat').hidden]") == [True, True], "Esc 关掉交给终端，回到对话")

    # B8：回复只按对应用户消息提示交给终端；偏好保存不得启动终端
    old_handoff = await pg.evaluate("__mock.cfg.handoff")
    handoff_go_before = await pg.evaluate("(__mock.hoGo || []).length")
    await pg.evaluate("__emit('menu', 'new_chat')")
    await pg.fill("#ask", "帮我改一下这个脚本的 bug"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("document.querySelector('#stopRow').hidden", timeout=5000)
    check(await pg.locator(".m.ai:last-of-type .meta .ho-hint").count() == 1, "代码类用户消息的回复末尾有「交给终端」")
    await shot("09h_reply_handoff")
    check(await pg.locator(".m.ai:last-of-type .meta").get_by_role("button", name="存为技能").count() == 1, "完成的回复可存为技能，和终端按钮同一行")
    await pg.click(".m.ai:last-of-type .skill-add")
    check("脚本的 bug" in await pg.input_value("#skillName") and "先把窗口" in await pg.input_value("#skillSteps"), "技能草稿使用对应问题和回复")
    await pg.fill("#skillName", "核对出处")
    await pg.fill("#skillWhen", "查资料时")
    await pg.fill("#skillSteps", "先找原文，再核对数字")
    await shot("09i_save_skill")
    await pg.evaluate("__mock.skillError = '配置写入失败'")
    await pg.click("#skillSave")
    await pg.wait_for_function("document.querySelector('#toast').textContent.includes('配置写入失败')")
    check(await pg.is_visible("#vSkill") and await pg.input_value("#skillSteps") == "先找原文，再核对数字", "保存失败时保留技能草稿")
    await pg.evaluate("delete __mock.skillError")
    await pg.click("#skillSave")
    await pg.wait_for_function("document.querySelector('#vSkill').hidden && __mock.cfg.skills?.length === 1")
    saved_skill = await pg.evaluate("__mock.cfg.skills[0]")
    check(saved_skill["name"] == "核对出处" and saved_skill["when"] == "查资料时" and saved_skill["steps"] == "先找原文，再核对数字", "发送已编辑的技能字段到本地保存入口")
    await pg.click(".m.ai:last-of-type .ho-hint")
    await pg.wait_for_selector("#vHo:not([hidden])")
    check("脚本的 bug" in await pg.input_value("#hoMd") and await pg.evaluate("(__mock.hoGo || []).length") == handoff_go_before, "回复按钮只打开对应交接预览，不启动终端")
    await pg.click("#hoCancel")
    await pg.evaluate("p => __TAURI__.core.invoke('save_handoff_prefs', p)", {"custom": old_handoff.get("custom", ""), "hint": False})
    await pg.wait_for_function("S.cfg.handoff.hint === false")
    await pg.fill("#ask", "再帮我写代码"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("document.querySelector('#stopRow').hidden", timeout=5000)
    check(await pg.locator(".m.ai:last-of-type .ho-hint").count() == 0, "关掉提示后，新的代码类回复不再出现按钮")
    await pg.evaluate("p => __TAURI__.core.invoke('save_handoff_prefs', p)", {"custom": old_handoff.get("custom", ""), "hint": True})
    await pg.wait_for_function("S.cfg.handoff.hint === true")
    await pg.fill("#ask", "请用一句话打个招呼"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("document.querySelector('#stopRow').hidden", timeout=5000)
    check(await pg.locator(".m.ai:last-of-type .ho-hint").count() == 0, "普通用户消息不会因为回复里有演示代码就误出终端提示")
    current_handoff = await pg.evaluate("__mock.cfg.handoff")
    check(all(current_handoff.get(k) == old_handoff.get(k) for k in ["tool", "term", "dirs", "save", "custom"]) and await pg.evaluate("(__mock.hoGo || []).length") == handoff_go_before, "保存提示偏好保留工具、终端、目录等选择，且不运行交接")
