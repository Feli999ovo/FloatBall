from ui_support import check


async def test_chat(orb_page):
    pg, shot, _ = orb_page
    # 1 首次启动：没 Key 也只显示小球，不自动弹出设置挡住屏幕
    await pg.wait_for_timeout(900)
    m = await shot("01_first_run_orb")
    check(m["size"] == {"w": 96, "h": 96}, f"首次启动只显示小球，不自动展开 {m['size']}")
    await pg.click("#orb"); await pg.wait_for_timeout(500)
    check(await pg.is_visible("#setupBtn") and not await pg.is_visible("#empty .chips"), "没设置模型时点开小球，提示先去设置")
    await shot("01b_first_run_tip")
    await pg.click("#setupBtn"); await pg.wait_for_timeout(200)
    check((await pg.evaluate("__mock")).get("settingsOpened") == 1, "点「去设置」打开设置窗口")
    check(await pg.evaluate("getComputedStyle(document.querySelector('#ask'), '::-webkit-scrollbar').display") == "none", "输入框不显示滚动条箭头")
    m = await pg.evaluate("__mock")
    bodycls = await pg.get_attribute("body", "class")
    check("flip-x" in bodycls, f"小球在右侧时卡片向左展开 ({bodycls})")
    eyes = await pg.evaluate("(() => { const o = document.querySelector('#orb').getBoundingClientRect(), b = document.querySelector('#bar').getBoundingClientRect(), a = document.querySelector('#ask').getBoundingClientRect(); return [o.left - b.left, a.left > o.right]; })()")
    check(abs(eyes[0]) < 1 and eyes[1], f"往左长时眼睛在胶囊左头、输入框在右边（照原型） {eyes}")
    check(m["pos"]["x"] + 364 <= 1440, f"展开后不超出屏幕右边 x={m['pos']['x']}")

    # 2 设置窗口里加好了模型：小球窗口收到通知，提示换成正常的引导
    await pg.evaluate("""() => {
        __mock.cfg.models = [{ id: 1, name: "", base_url: "https://api.openai.com/v1", model: "gpt-4o-mini", vision: true, no_key: false, has_key: true }];
        __mock.cfg.default_model = 1;
        __emit("config");
    }""")
    await pg.wait_for_timeout(200)
    check(not await pg.is_visible("#setupBtn") and await pg.is_visible("#empty .chips"), "加好模型后不再提示去设置")

    # 3 空状态
    check(await pg.is_visible("#empty"), "空对话显示引导")
    await shot("03_empty_chat")

    # 4 发消息，流式输出
    await pg.evaluate("__mock.slow = true")
    await pg.fill("#ask", "怎么开始开发悬浮球？")
    await pg.press("#ask", "Enter")
    await pg.wait_for_timeout(300)
    cls = await pg.get_attribute("#orb", "class")
    check("s-think" in cls, f"等待时小球是思考表情 ({cls})")
    await pg.wait_for_timeout(1300)
    cls = await pg.get_attribute("#orb", "class")
    check("s-think" in cls, f"输出文字时小球保持思考的光点（照原型） ({cls})")
    dots = await pg.evaluate("[...document.querySelectorAll('#orb .orbit b')].map((b) => getComputedStyle(b).animationName)")
    check(dots == ["orbit"] * 3, f"三颗光点在转 {dots}")
    check(await pg.is_visible("#stopRow"), "生成中显示停止按钮")
    check(await pg.is_hidden("#empty"), "有消息时隐藏空状态引导")
    await shot("04_streaming")
    await pg.evaluate("__mock.slow = false")
    await pg.wait_for_function("!__mock.calls.includes('x') && document.querySelector('.m.ai .meta') && !document.querySelector('.m.ai .meta').hidden", timeout=15000)
    html = await pg.inner_html(".m.ai .txt")
    check("<ol>" in html and "<pre><code>" in html and "<b>" in html, "Markdown：列表、代码块、粗体")
    check("tokens" in await pg.inner_text(".m.ai .meta"), "完成后显示用量")
    cls = await pg.get_attribute("#orb", "class")
    check("s-done" in cls, f"完成后小球眯眼笑 ({cls})")
    check(await pg.evaluate("getComputedStyle(document.querySelector('#orb .spark')).animationName") == "twinkle", "完成时角上有小星星（照原型）")
    await pg.wait_for_timeout(1700)
    cls = await pg.get_attribute("#orb", "class")
    check("s-done" not in cls, f"1.5 秒后不再是完成表情 ({cls})")
    await shot("05_done")
    await pg.click(".m.ai .meta button:has-text('复制')")
    clip = await pg.evaluate("navigator.clipboard.readText()")
    check("三个要点" in clip, "复制回复")

    # 5 停止
    await pg.evaluate("__mock.slow = true")
    await pg.fill("#ask", "再说一遍"); await pg.press("#ask", "Enter")
    await pg.wait_for_timeout(1100)
    await pg.click("#stopBtn"); await pg.wait_for_timeout(200)
    last = pg.locator(".m.ai").last
    check("已停止" in await last.inner_text(), "停止生成")
    check(await pg.is_hidden("#stopRow"), "停止后按钮消失")
    await pg.evaluate("__mock.slow = false")

    # 6 出错 + 重试按钮
    await pg.fill("#ask", "制造一个错误"); await pg.press("#ask", "Enter")
    await pg.wait_for_selector(".m.ai.err", timeout=5000)
    check("401" in await pg.locator(".m.ai.err").inner_text(), "错误信息显示")
    check("s-error" in await pg.get_attribute("#orb", "class"), "出错时小球表情")
    check(await pg.locator(".m.ai.err .meta button:has-text('重试')").count() == 1, "错误有重试按钮")
    await shot("06_error")

    # 6b Agent 用工具：药丸显示在做什么；删除先停下来等确认（原型的 toolChip / askAppr）
    await pg.fill("#ask", "删除下载文件夹里重复的报告"); await pg.press("#ask", "Enter")
    await pg.wait_for_selector(".x-ap", timeout=5000)
    last = pg.locator(".m.ai").last
    pills = await last.locator(".x-tw").evaluate_all("ws => ws.map(w => [w.className, w.querySelector('.x-tl').textContent])")
    check(pills == [["x-tw done", "查看文件夹 · /Users/j/Downloads"], ["x-tw wait", "删除文件 · 报告 (1).pdf"]], f"工具药丸：完成的 ✓、等确认的暂停 {pills}")
    check("我先看看下载文件夹。" in await last.locator(".txt").first.inner_text(), "药丸前的文字")
    ap = await last.locator(".x-ap").inner_text()
    check("高风险" in ap and "删除 /Users/j/Downloads/报告 (1).pdf" in ap and "允许一次" in ap and "总是允许" in ap, f"确认卡片 {ap!r}")
    oc = await pg.get_attribute("#orb", "class")
    check("s-wait" in oc and "need" in oc, f"等确认时小球是「等你」表情（同原型 setState('wait')）{oc}")
    await shot("06b_ask")
    check(await pg.evaluate("getComputedStyle(document.querySelector('#orb .need')).opacity") == "0", "卡片开着时不显示「!」")
    await pg.evaluate("collapse()"); await pg.wait_for_timeout(800)
    g = await pg.evaluate("""(() => { const n = document.querySelector('#orb .need'), o = document.querySelector('#orb').getBoundingClientRect(), r = n.getBoundingClientRect(),
        ring = getComputedStyle(document.querySelector('#orb .breath'), '::before');
        return { op: getComputedStyle(n).opacity, txt: n.textContent, topRight: r.right <= o.right + 1 && r.left > o.left + o.width / 2 && r.top < o.top + o.height / 3,
                 ring: ring.content !== 'none' && ring.borderTopStyle === 'solid', eyeTop: getComputedStyle(document.querySelector('#orb .eye')).animationName }; })()""")
    check(g["op"] == "1" and g["txt"] == "!" and g["topRight"], f"收起后球右上角亮「!」{g}")
    check(g["ring"] and g["eyeTop"] == "slowblink", f"收起后「等你」：暖白呼吸光环 + 慢速眨眼 {g}")
    await shot("06b2_wait_orb")
    await pg.evaluate("document.body.classList.add('x'); document.querySelector('#orb').dataset.edge = 'r'"); await pg.wait_for_timeout(300)
    g2 = await pg.evaluate("(() => { const n = document.querySelector('#orb .need').getBoundingClientRect(), o = document.querySelector('#orb').getBoundingClientRect(); return n.left < o.left + o.width / 2; })()")
    check(g2, "贴右边时「!」换到左上角")
    await pg.evaluate("document.querySelector('#orb').dataset.edge = ''")
    await pg.click("#orb"); await pg.wait_for_timeout(900)
    last = pg.locator(".m.ai").last
    await last.locator(".x-tw.done .x-tool").click()
    check("报告 (1).pdf（20480 字节）" in await last.locator(".x-tw.done .x-tres").inner_text(), "点完成的药丸看结果")
    await last.locator(".x-ap button:has-text('允许一次')").click()
    await pg.wait_for_function("document.querySelector('.m.ai:last-of-type .meta') && !document.querySelector('.m.ai:last-of-type .meta').hidden", timeout=5000)
    m = await pg.evaluate("__mock.answers[__mock.answers.length - 1]")
    check(m == {"ask": 7, "answer": {"allow": True, "always": False, "reason": "", "edit": ""}}, f"允许一次传回 Rust {m}")
    txts = await last.locator(".txt").all_inner_texts()
    check(txts == ["我先看看下载文件夹。", "删好了，重复的那份在悬浮球回收站里。"], f"药丸后面的字另起一段 {txts}")
    nd, meta = await last.locator(".x-ap button:disabled").count(), await last.locator(".meta").inner_text()
    await last.get_by_role("button", name="明细", exact=True).click()
    check(nd >= 4 and "1.8K tokens" in await last.locator(".receipt").inner_text(), f"确认后按钮变灰，结束显示用量 {nd} {meta!r}")
    await last.get_by_role("button", name="收起明细", exact=True).click()
    check("need" not in await pg.get_attribute("#orb", "class"), "确认后去掉「!」")
    hist = await pg.evaluate("__mock.convs[0].msgs.slice(-1)[0].content")
    check(hist == "我先看看下载文件夹。\n\n删好了，重复的那份在悬浮球回收站里。", f"历史里存整条回复 {hist!r}")
    await shot("06c_allowed")
    # 拒绝并说明原因
    await pg.fill("#ask", "删除那个旧的"); await pg.press("#ask", "Enter")
    await pg.wait_for_selector(".m.ai:last-of-type .x-ap", timeout=5000)
    last = pg.locator(".m.ai").last
    await last.locator(".x-ap .x-apx").click(); await last.locator(".x-ap button:has-text('拒绝并说明')").click()
    await last.locator(".x-apr input").fill("还要用"); await last.locator(".x-apr button").click()
    await pg.wait_for_timeout(300)
    m = await pg.evaluate("__mock.answers[__mock.answers.length - 1]")
    check(m["answer"]["allow"] is False and m["answer"]["reason"] == "还要用", f"拒绝原因传回 {m}")
    check("已拒绝" in await last.locator(".x-tw.no").inner_text() and "好的，没删。" in await last.inner_text(), "拒绝后药丸标已拒绝")

    # 6c 多 Agent（B1，照原型 runTeam / agRow）：主控交给研究员 / 整理员 / 写手，对话里出计划卡；任务页顶上 Agents 头像条 + 弹卡
    await pg.evaluate("""() => { const A = (id, name, role, tint, tools) => ({ id, name, role, tint, emoji: "", tools, prompt: "", model: 0, fallback: 0, auto: false });
        __mock.cfg.agents = [__mock.cfg.agents[0], A("research", "研究员", "搜索与阅读", "#A9BEDB", ["读文件"]), A("organize", "整理员", "文件与表格", "#AECDB6", ["读文件", "写文件"]), A("writer", "写手", "起草与润色", "#DCC0A8", ["读文件", "写文件"])];
        __mock.holdTeam = true; __emit("config"); }""")
    await pg.wait_for_timeout(300)
    await pg.fill("#ask", "帮我调研三款降噪耳机并写个对比报告"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("document.querySelectorAll('.m.ai:last-of-type .x-plan .x-ps').length === 3 && document.querySelector('.m.ai:last-of-type .x-ps[data-call=t1]').dataset.st === 'run'", timeout=5000)
    plan = await pg.evaluate("""(() => { const c = document.querySelector('.m.ai:last-of-type .x-plan');
        return { h: c.querySelector('.x-plh').textContent, f: c.querySelector('.x-plf').textContent,
                 rows: [...c.querySelectorAll('.x-ps')].map(r => [r.querySelector('b').textContent, r.querySelector('.x-pss').textContent, r.dataset.st, r.querySelector('.x-pst').textContent, r.querySelector('.x-ptk').textContent]),
                 pm: c.querySelector('.x-pm').textContent, av: getComputedStyle(c.querySelector('.x-av')).getPropertyValue('--t').trim(),
                 before: c.previousElementSibling && c.previousElementSibling.textContent }; })()""")
    check(plan["h"] == "主控 · 3 步计划 · 点一步看为什么交给它", f"计划卡标题同原型 {plan['h']}")
    check(plan["rows"] == [["研究员", "搜集 3 款耳机评测", "done", "✓", "6.1K · ¥0.05"], ["整理员", "做参数对比表", "run", "进行中", ""], ["写手", "写对比报告", "wait", "等待", ""]], f"每步：谁、做什么、状态、用量和花费 {plan['rows']}")
    handoffs = await pg.locator(".x-ph").count()
    check(handoffs == 1 and "研究员 → 整理员：已交接 1 段结果" in await pg.locator(".x-ph").inner_text(), "步骤交给下一位 Agent 前显示交接行并传递结果数量")
    check(plan["f"] == "共 6.1K tokens" and plan["pm"] == "gpt-4o-mini" and plan["av"] == "#A9BEDB", f"底部合计、模型标签、头像颜色 {plan}")
    check("拆成 3 步" in (plan["before"] or ""), "主控的话在计划卡前面")
    await pg.click(".m.ai:last-of-type .x-ps[data-call=t0]"); await pg.wait_for_timeout(150)
    why = await pg.inner_text(".m.ai:last-of-type .x-pwhy:not([hidden])")
    check("研究员的职责是「搜索与阅读」" in why and "读文件" in why, f"点一步看为什么交给它 {why!r}")
    await shot("06d_team")
    await pg.click("#tabTask"); await pg.wait_for_timeout(300)
    ags = await pg.evaluate("[...document.querySelectorAll('#tasks .x-ags .x-ag')].map(b => [b.textContent, b.dataset.st])")
    check(await pg.inner_text("#tasks .x-ags .x-hg") == "Agents" and ags == [["研究员", "idle"], ["整理员", "busy"], ["写手", "idle"]], f"任务页 Agents 头像条：忙的亮橙点 {ags}")
    await pg.click("#tasks .x-ag[data-ag=organize]"); await pg.wait_for_timeout(200)
    pop = await pg.evaluate("(() => { const p = document.querySelector('#tasks .x-agp'), r = p.getBoundingClientRect(), c = document.querySelector('#card').getBoundingClientRect(); return { hidden: p.hidden, t: p.innerText, inside: r.left >= c.left && r.right <= c.right + 1 }; })()")
    check(not pop["hidden"] and "整理员" in pop["t"] and "文件与表格" in pop["t"] and "模型 · gpt-4o-mini（默认）" in pop["t"] and "忙碌 · 做参数对比表" in pop["t"] and pop["inside"], f"Agent 弹卡：职责、模型、在忙什么 {pop}")
    await shot("06e_agents")
    await pg.click("#tasks .x-agp .x-agx"); await pg.wait_for_timeout(150)
    check((await pg.evaluate("__mock")).get("settingsAgent") == "organize" and await pg.evaluate("document.querySelector('#tasks .x-agp').hidden"), "「更换」打开设置里这个 Agent 的编辑页")
    await pg.evaluate("__mock.teamNext()")
    await pg.wait_for_function("document.querySelector('.m.ai:last-of-type .meta') && !document.querySelector('.m.ai:last-of-type .meta').hidden", timeout=5000)
    await pg.click("#tabTask"); await pg.wait_for_timeout(300)
    ags = await pg.evaluate("[...document.querySelectorAll('#tasks .x-ags .x-ag')].map(b => b.dataset.st)")
    await pg.click("#tabChat"); await pg.wait_for_timeout(200)
    fin = await pg.evaluate("(() => { const c = document.querySelector('.m.ai:last-of-type .x-plan'); return [[...c.querySelectorAll('.x-ps')].map(r => r.dataset.st), c.querySelector('.x-plf').textContent, c.nextElementSibling.textContent]; })()")
    check(fin[0] == ["done", "done", "done"] and "共 18.4K tokens · 约 ¥0.17（默认汇率）" == fin[1] and fin[2] == "报告写好了：通勤选索尼，强降噪选 Bose。" and ags == ["idle", "idle", "idle"], f"做完：三步打勾、汇总人民币花费和结论 {fin} {ags}")
    check("约 ¥0.19（默认汇率）" in await pg.inner_text(".m.ai:last-of-type .meta"), "最后回复显示整次多 Agent 请求的人民币估算")
    await shot("06f_team_done")
    await pg.evaluate("__mock.teamUnknown = true; __mock.holdTeam = true; __mock.repeatTeamAgent = true")
    await pg.fill("#ask", "请再调研一次耳机"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("__mock.lastMessages?.at(-1)?.content === '请再调研一次耳机' && typeof __mock.teamNext === 'function'")
    await pg.evaluate("__mock.teamNext()")
    await pg.wait_for_function("!S.busy && document.querySelector('.m.ai:last-of-type .meta') && !document.querySelector('.m.ai:last-of-type .meta').hidden")
    check("约 ¥" not in await pg.inner_text(".m.ai:last-of-type .x-plan .x-plf") and "约 ¥" not in await pg.inner_text(".m.ai:last-of-type .meta"), "未知单价时不显示估算花费")
    placement = await pg.evaluate("""() => {
        const rows = [...document.querySelectorAll('.m.ai:last-of-type .x-plan :is(.x-ps, .x-ph)')];
        return rows.map(row => row.dataset.call ? [row.dataset.call, row.querySelector('b').textContent] : row.dataset.handoff);
    }""")
    check(placement == [["t0", "研究员"], "t0-t1", ["t1", "整理员"], "t1-t2", ["t2", "研究员"]], f"同名 Agent 的交接行按目标步骤插入，目标晚到也能插对 {placement}")
    await pg.evaluate("__mock.repeatTeamAgent = false; __mock.teamUnknown = false; __mock.teamLocal = true; __mock.holdTeam = true")
    await pg.fill("#ask", "再用本地模型调研一次"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("typeof __mock.teamNext === 'function'")
    await pg.evaluate("__mock.teamNext()")
    await pg.wait_for_function("!S.busy && document.querySelector('.m.ai:last-of-type .meta') && !document.querySelector('.m.ai:last-of-type .meta').hidden")
    check("Ollama · llama3" in await pg.inner_text(".m.ai:last-of-type .x-plan") and "约 ¥" not in await pg.inner_text(".m.ai:last-of-type .x-plan .x-plf"), "本地模型按零花费处理，不显示单价估算")
    await pg.evaluate("__mock.teamLocal = false")

    await pg.click("#tabTask")
    await pg.click("#tasks .x-ag[data-ag=research]")
    await pg.wait_for_function("document.querySelector('.x-agp .memory-count')?.textContent.includes('0 条')")
    await pg.click("#tabChat")
    await pg.evaluate("__mock.rememberNext = {agent:'research', text:'用户喜欢用中文'}")
    await pg.fill("#ask", "请记住我喜欢用中文"); await pg.press("#ask", "Enter")
    await pg.wait_for_function("__mock.memories?.research?.length === 1 && !S.busy")
    await pg.click("#tabTask")
    await pg.click("#tasks .x-ag[data-ag=research]")
    await pg.wait_for_function("document.querySelector('.x-agp .memory-count')?.textContent.includes('1 条')")
    check(await pg.inner_text(".x-agp .memory-count") == "独立记忆 · 1 条", "记住偏好后，Agent 弹卡条数增加")
