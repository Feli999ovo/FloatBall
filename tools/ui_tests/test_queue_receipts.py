from ui_support import check, enable_model


async def test_queue_receipts(orb_page):
    pg, shot, errs = orb_page
    await enable_model(pg)
    # P1 只规划、后台排队和输入历史
    await pg.evaluate("async () => { newChat(); __mock.chatProbe = []; await expand('chat'); }")
    await pg.click("#planToggle")
    check(await pg.get_attribute("#planToggle", "aria-pressed") == "true" and await pg.is_visible("#planBanner") and await pg.get_attribute("#ask", "placeholder") == "先出方案…", "只规划切换、横幅和占位文字")
    for prompt in ["第一条规划", "第二条排队", "第三条排队", "取消这一条"]:
        await pg.fill("#ask", prompt)
        await pg.press("#ask", "Enter")
    check(await pg.locator(".m.queued").count() == 3 and await pg.evaluate("__mock.chatProbe.map(p => [p.q, p.plan])") == [["第一条规划", True]], "生成中接收待发消息，未提前传给后端")
    await pg.locator(".m.queued").last.get_by_role("button", name="删除待发消息").click()
    await shot("p1_plan_and_queue")
    await pg.evaluate("window.__planConv = S.conv; newChat()")
    check(await pg.get_attribute("#planToggle", "aria-pressed") == "false", "新对话默认执行")
    for count in [2, 3]:
        await pg.evaluate("__mock.finishChatProbe()")
        await pg.wait_for_function(f"__mock.chatProbe.length === {count}")
    await pg.evaluate("__mock.finishChatProbe(); goConv(__planConv)")
    check(await pg.evaluate("__mock.chatProbe.map(p => p.q)") == ["第一条规划", "第二条排队", "第三条排队"], "切走后原对话按顺序发出队列，已取消的消息不发送")
    await pg.locator(".m.ai").last.get_by_role("button", name="改成执行").click()
    check(await pg.get_attribute("#planToggle", "aria-pressed") == "false" and await pg.input_value("#ask") == "按上面的方案执行", "改成执行填好草稿，等用户发送")
    await pg.fill("#ask", "未发送的草稿")
    for prompt in ["第三条排队", "第二条排队", "第一条规划"]:
        await pg.press("#ask", "ArrowUp")
        check(await pg.input_value("#ask") == prompt, "上翻输入历史 " + prompt)
    for _ in range(3):
        await pg.press("#ask", "ArrowDown")
    check(await pg.input_value("#ask") == "未发送的草稿", "下翻到底恢复草稿")
    await pg.evaluate("document.querySelector('#ask').dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowUp', isComposing:true}))")
    check(await pg.input_value("#ask") == "未发送的草稿", "输入法组字期间不翻历史")
    await pg.evaluate("newTmpChat()")
    for prompt in ["临时问题", "停止后不发送"]:
        await pg.fill("#ask", prompt)
        await pg.press("#ask", "Enter")
    await pg.click("#stopBtn")
    await pg.evaluate("__mock.finishChatProbe()")
    check("没发出" in await pg.locator(".m.queued").inner_text() and await pg.evaluate("__mock.chatProbe.length") == 4, "停止后待发消息留待手动处理")
    check(await pg.evaluate("!JSON.parse(localStorage.getItem('fb.askHistory')).includes('临时问题')"), "临时对话不进输入历史")
    await pg.locator(".m.queued").get_by_role("button", name="重新发送").click()
    await pg.evaluate("__mock.finishChatProbe(); delete __mock.chatProbe; delete __mock.finishChatProbe; newChat()")
    check(not errs, "P1 界面无 JS 错误 " + "; ".join(errs))

    # P3 收据按调用编号去重、保留同名文件的完整路径。
    await pg.fill("#ask", "一个普通问题")
    await pg.press("#ask", "Enter")
    await pg.wait_for_function("!S.busy")
    check(await pg.locator(".receipt").count() == 0, "没有工具调用就没有收据")
    await pg.evaluate("newChat(); __mock.receiptProbe = 'done'")
    await pg.fill("#ask", "核对两份周报")
    await pg.press("#ask", "Enter")
    await pg.get_by_role("button", name="允许一次", exact=True).click()
    await pg.wait_for_function("!S.busy")
    check("3 步 · 读 2 · 写 1 · 确认 1" in await pg.locator(".receipt-summary").inner_text(), "收据摘要按调用去重，读写确认数字准确")
    await pg.get_by_role("button", name="明细", exact=True).click()
    receipt = await pg.locator(".receipt").inner_text()
    check(all(s in receipt for s in ["完成", "D:/旧版/周报.txt", "D:/本周/周报.txt", "D:/本周/汇总.txt", "允许 1 次 · 拒绝 0 次", "240 tokens", "¥0.03"]), "收据明细显示同名文件全路径、确认、用量和花费")
    await shot("p3_receipt")
    await pg.evaluate("newChat(); __mock.receiptProbe = 'stop'")
    await pg.fill("#ask", "停止检查")
    await pg.press("#ask", "Enter")
    await pg.wait_for_function("document.querySelectorAll('.x-tw.done').length === 2")
    await pg.click("#stopBtn")
    await pg.get_by_role("button", name="明细", exact=True).click()
    check("已停止" in await pg.locator(".receipt").inner_text() and "未知" in await pg.locator(".receipt").inner_text(), "停止时仍有收据，花费未知")
    await pg.evaluate("newChat(); __mock.receiptProbe = 'changes'; S.cfg.agents = [S.cfg.agents[0], {id: 'same', name: '同模型', model: 0, tools: []}, {id: 'reviewer', name: '审查员', model: 2, tools: []}]; S.cfg.models.push({id: 2, name: '审查模型', model: 'test-review'})")
    await pg.fill("#ask", "整理项目文件")
    await pg.press("#ask", "Enter")
    await pg.get_by_role("button", name="允许一次", exact=True).click()
    await pg.wait_for_function("!S.busy")
    await pg.get_by_role("button", name="这一轮改了 3 个文件 · 查看", exact=True).click()
    rows = pg.locator(".file-changes > div")
    check(await rows.count() == 3, "改动清单有三条记录")
    check([(await rows.nth(i).locator("span").inner_text()).split(" · ")[0] for i in range(3)] == ["删", "改", "新"], "改动清单标出新、改、删")
    await shot("p4_changes")
    await pg.get_by_role("button", name="请别的 Agent 审查").click()
    check(await pg.get_by_role("combobox", name="审查 Agent").input_value() == "reviewer", "审查默认推荐不同模型的 Agent")
    await pg.get_by_role("button", name="开始审查").click()
    await pg.wait_for_function("!S.busy && __mock.reviewRequest")
    request = await pg.evaluate("__mock.reviewRequest")
    check(request["plan"] and request["reviewAgent"] == "reviewer" and all(p in request["q"] for p in ["D:/本周/总结.txt", "D:/数据/改动备份/汇总.txt", "D:/旧版/失效.txt"]), "选中的 Agent 收到只规划与新旧路径")
    review_reply = pg.locator(".m.ai").last
    check("审查 · 审查员" in await review_reply.inner_text() and "审查结论：请补充说明" in await review_reply.inner_text() and await rows.count() == 3, "审查回复带标题，留在原对话")
    await rows.nth(1).get_by_role("button", name="撤回", exact=True).click()
    check(await pg.is_visible("#changeQ") and not await pg.evaluate("__mock.undoResults"), "撤回前先确认，尚未调用后端")
    await pg.click("#changeOk")
    await pg.wait_for_function("document.querySelector('#changeOk').textContent === '仍要撤回'")
    check("之后又被改过" in await pg.inner_text("#changeQT"), "文件后来改过时要求再确认一次")
    await pg.click("#changeOk")
    await rows.nth(1).get_by_role("button", name="已撤回", exact=True).wait_for()
    check(await pg.evaluate("__mock.undoResults.map(a => [a.id, a.confirmChanged])") == [["modify", False], ["modify", True]], "撤回成功后显示已撤回，第二次明确确认")
    await rows.nth(0).get_by_role("button", name="撤回", exact=True).click()
    await pg.click("#changeOk")
    await pg.wait_for_function("document.querySelector('#toast').textContent.includes('原位置已经有同名文件')")
    assert await pg.get_by_role("button", name="重新加载").is_visible()
    check(await rows.nth(0).get_by_role("button", name="撤回", exact=True).is_enabled(), "同名冲突说明没有撤回，按钮状态保留")
    await pg.evaluate("delete __mock.receiptProbe; newChat(); __mock.pendingProbe = true")
    for prompt in ["待办用例 写入", "待办用例 预算"]:
        await pg.fill("#ask", prompt)
        await pg.press("#ask", "Enter")
        await pg.evaluate("newChat()")
    await pg.wait_for_function("pendingCards.size === 2")
    await pg.click("#tabTask")
    check(await pg.locator("#tasks .pending-row").count() == 2 and await pg.inner_text("#tBadge") == "4", "两个后台卡都集中到待办，角标加上待办数")
    await shot("p5_pending")
    await pg.get_by_role("button", name="待办用例 写入 · 待确认写入测试").click()
    check(await pg.is_visible("#vChat") and await pg.inner_text("#title") == "待办用例 写入" and await pg.evaluate("document.activeElement.closest('.x-ap') !== null"), "点待办回对应对话并聚焦确认卡")
    await pg.get_by_role("button", name="允许一次", exact=True).click()
    await pg.wait_for_function("!S.busy")
    await pg.click("#tabTask")
    check(await pg.locator("#tasks .pending-row").count() == 1 and await pg.inner_text("#tBadge") == "2", "处理后只移除对应待办，预算暂停仍在")
    await pg.get_by_role("button", name="待办用例 预算 · 预算用完，已暂停").click()
    await pg.locator(".x-ap").get_by_role("button", name="停止", exact=True).click()
    await pg.wait_for_function("!S.busy")
    await pg.click("#tabTask")
    check(await pg.locator("#pendingHead").count() == 0 and await pg.is_hidden("#tBadge"), "待办处理完后隐藏分组和角标")
    await pg.evaluate("delete __mock.pendingProbe; newChat()")
    await pg.click("#tabChat")
