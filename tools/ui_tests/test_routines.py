from ui_support import check, enable_model


async def test_routines(orb_page):
    pg, shot, _ = orb_page
    await enable_model(pg)
    await pg.click('#orb')
    await pg.fill('#ask', '初始化已完成任务')
    await pg.press('#ask', 'Enter')
    await pg.wait_for_selector('.m.ai .meta:not([hidden])')
    # 9b 定时任务（B5）：任务页「定时任务」一组；新建、下次时间、开关、到点在后台跑、运行记录、删除
    await pg.click("#tabTask"); await pg.wait_for_timeout(200)
    heads = await pg.evaluate("[...document.querySelectorAll('#tasks .hg')].map(h => h.textContent)")
    check(heads == ["定时任务", "已完成"], f"任务页照原型分组 {heads}")
    await pg.click("#tasks .rtadd"); await pg.wait_for_timeout(150)
    check(await pg.evaluate("document.activeElement.id") == "rtEdprompt", "新建：光标在「指令」")
    await pg.click("#tasks .rd .x-pri"); await pg.wait_for_timeout(150)
    check(await pg.evaluate("document.activeElement.id") == "rtEdprompt" and not await pg.evaluate("(__mock.cfg.routines || []).length"), "指令空着不能保存")
    await pg.fill("#rtEdprompt", "汇总今天的未读邮件")
    await pg.select_option("#rtEdevery", "week"); await pg.wait_for_timeout(50)
    check(await pg.is_visible("#rtEdweekday"), "选「每周」才出星期几")
    await pg.select_option("#rtEdweekday", "5"); await pg.fill("#rtEdtime", "17:30")
    await pg.evaluate("__mock.rtNextAt = Math.floor(new Date(new Date().setHours(17, 30, 0, 0)).getTime() / 1000) + 86400")
    await pg.click("#tasks .rd .x-pri"); await pg.wait_for_timeout(300)
    r = await pg.evaluate("__mock.cfg.routines[0]")
    check((r["id"], r["name"], r["every"], int(r["weekday"]), r["time"], r["on"]) == ("rt1", "汇总今天的未读邮件", "week", 5, "17:30", True), f"保存新的定时任务 {r}")
    row = await pg.evaluate("(() => { const d = document.querySelector('#tasks .tk.rt'); return d && [d.querySelector('.name').textContent, d.querySelector('.rts').textContent, d.querySelector('.x-sw').getAttribute('aria-checked'), !!d.querySelector('.rd')]; })()")
    check(row == ["汇总今天的未读邮件", "每周五 17:30 · 下次 明天 17:30", "true", False], f"定时任务一行：名字、何时运行、下次时间、开关 {row}")
    await pg.click("#tasks .tk.rt .x-sw"); await pg.wait_for_timeout(200)
    row = await pg.evaluate("[__mock.cfg.routines[0].on, document.querySelector('#tasks .tk.rt .rts').textContent, document.querySelector('#tasks .tk.rt').classList.contains('off')]")
    check(row == [False, "每周五 17:30 · 已关闭", True], f"点开关关掉 {row}")
    await pg.click("#tasks .tk.rt .x-sw"); await pg.wait_for_timeout(200)
    # 到点：后端发 routine 事件 → 开一个新对话在后台跑，当前对话不动，跑完记一条运行记录
    await pg.click("#tabChat"); await pg.wait_for_timeout(100)
    await pg.evaluate("__emit('menu', 'new_tmp')"); await pg.wait_for_timeout(800)
    before = await pg.evaluate("[document.querySelector('#title').textContent, document.querySelectorAll('.m').length]")
    await pg.evaluate("__emit('routine', __mock.cfg.routines[0])"); await pg.wait_for_timeout(100)
    after = await pg.evaluate("[document.querySelector('#title').textContent, document.querySelectorAll('.m').length, document.querySelector('#tmpBanner').hidden]")
    check(after[:2] == before and after[2] is False, f"临时对话前台时定时任务在后台运行，前台保持临时 {before} → {after}")
    await pg.wait_for_function("(__mock.rtDone || []).length", timeout=15000)
    check(await pg.evaluate("__mock.rtDone[0]") == ["rt1", True, "按时运行"], f"跑完记运行记录 {await pg.evaluate('__mock.rtDone')}")
    await pg.wait_for_function("__mock.convs.some(c => c.msgs.some(m => m.content === '汇总今天的未读邮件'))")
    routine_hist = await pg.evaluate("__mock.convs.some(c => c.msgs.some(m => m.content === '汇总今天的未读邮件'))")
    check(routine_hist, "临时对话在前台时，定时任务自己的普通会话仍保存历史")
    await pg.click("#tabTask"); await pg.wait_for_timeout(250)
    names = await pg.evaluate("[...document.querySelectorAll('#tasks .tk:not(.rt) .name')].map(n => n.textContent)")
    check(names[0] == "定时 · 汇总今天的未读邮件", f"任务页列出这次运行，名字带「定时」 {names[:2]}")
    await pg.click("#tasks .tk.rt .name"); await pg.wait_for_timeout(150)
    det = await pg.evaluate("(() => { const d = document.querySelector('#tasks .tk.rt .rd'); return d && [[...d.querySelectorAll('dt')].map(x => x.textContent), d.querySelector('li').textContent.replace(/\\s+/g, ' ').trim(), document.querySelector('#tasks .tk.rt .name').getAttribute('aria-expanded')]; })()")
    check(det and det[0] == ["指令", "何时运行", "下次运行", "运行记录"] and det[1].startswith("✓ 成功") and det[1].endswith("按时运行") and det[2] == "true", f"点名字展开详情：指令、时间、运行记录 {det}")
    await pg.click("#tasks .rd .x-sb:has-text('编辑')"); await pg.wait_for_timeout(150)
    check(await pg.evaluate("[document.activeElement.id, document.querySelector('#rtEdprompt').value]") == ["rtEdprompt", "汇总今天的未读邮件"], "编辑：带出原来的指令")
    await pg.fill("#rtEdprompt", "汇总未读邮件并分组"); await pg.click("#tasks .rd .x-pri"); await pg.wait_for_timeout(250)
    check(await pg.evaluate("[__mock.cfg.routines.length, __mock.cfg.routines[0].prompt, __mock.cfg.routines[0].id]") == [1, "汇总未读邮件并分组", "rt1"], "编辑后保存的是同一个，不会多出一个")
    await pg.click("#tasks .rd .x-sb:has-text('删除')"); await pg.wait_for_timeout(100)
    check(await pg.evaluate("(__mock.cfg.routines || []).length") == 1, "删除要再点一次确认")
    await pg.click("#tasks .rd .x-sb:has-text('确认删除')"); await pg.wait_for_timeout(250)
    check(await pg.evaluate("[(__mock.cfg.routines || []).length, document.querySelectorAll('#tasks .tk.rt').length]") == [0, 0], "确认删除后没有了")

    # P2 触发规则由 Rust 测试，浏览器覆盖表单与运行参数。
    for i, (every, prompt, summary) in enumerate([
        ("workday", "工作日写周报", "工作日 09:00"), ("month", "月末写周报", "每月 31 号 09:00"), ("once", "只写一次周报", "11月30日 09:00 一次"),
    ], start=1):
        await pg.click("#tasks .rtadd")
        await pg.fill("#rtEdprompt", prompt)
        await pg.select_option("#rtEdevery", every)
        if every == "month":
            await pg.select_option("#rtEdmonthday", "31")
        elif every == "once":
            await pg.fill("#rtEddate", "2000-01-01")
            await pg.click("#tasks .rd .x-pri")
            await pg.wait_for_function("document.querySelector('#toast').textContent.includes('这个时间已经过了')")
            check(await pg.evaluate("__mock.cfg.routines.length") == 2, "过期的一次性任务不能保存")
            await pg.fill("#rtEddate", "2099-11-30")
        elif every == "workday":
            await pg.click("#tasks .rt-allow summary")
            await pg.get_by_role("checkbox", name="写文件", exact=True).check()
            await shot("p2_routine_permissions")
        await pg.click("#tasks .rd .x-pri")
        await pg.wait_for_function(f"document.querySelectorAll('#tasks .tk.rt').length === {i} && !document.querySelector('#rtEdprompt')")
        check(summary in await pg.locator("#tasks .tk.rt").nth(i - 1).locator(".rts").inner_text(), "任务行显示 " + summary)
    await pg.locator('#tasks .tk.rt[data-rid="rt1"] .name').click()
    await pg.get_by_role("button", name="编辑", exact=True).click()
    await pg.click("#tasks .rt-allow summary")
    check(await pg.get_by_role("checkbox", name="写文件", exact=True).is_checked() and not await pg.get_by_role("checkbox", name="打开网页", exact=True).is_checked(), "预授权只保存勾选项")
    await pg.get_by_role("button", name="取消", exact=True).click()
    await pg.evaluate("__mock.routineProbe = '工作日写周报'; __emit('routine', __mock.cfg.routines[0])")
    await pg.wait_for_function("(__mock.rtDone || []).length === 2")
    await pg.locator("#tasks .tk:not(.rt) .name").first.click()
    check(await pg.evaluate("__mock.lastRoutineAllow") == ["写入"] and await pg.locator(".x-ap").count() == 0 and "已预授权" in await pg.locator(".x-tl").inner_text(), "到点运行只传自己的预授权，写入直接显示药丸")
    await pg.evaluate("delete __mock.routineProbe; __mock.cfg.routines = []; __emit('config')")
    await pg.click("#tabChat"); await pg.wait_for_timeout(100)
